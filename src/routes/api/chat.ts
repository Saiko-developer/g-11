type ChatRequestBody = {
  messages?: unknown;
  lessonContext?: string;
  currentQuestion?: string | null;
  mode?: "voice" | "text";
};

export const Route = createFileRoute("/api/chat")({
  server: {
    handlers: {
      POST: async ({ request }) => {
        const blocked = await consumeTutorQuota(request);
        if (blocked) return blocked;
        const body = (await request.json()) as ChatRequestBody;
        const { messages, lessonContext, currentQuestion, mode } = body;
        if (!Array.isArray(messages)) {
          return new Response("Messages are required", { status: 400 });
        }

        if (!process.env.LOVABLE_API_KEY) {
          return new Response("Missing LOVABLE_API_KEY", { status: 500 });
        }
        const model = getLovableChatModel();

        let system = mode === "voice" ? VOICE_PROMPT : mode === "text" ? TEXT_PROMPT : BASE_PROMPT;
        if (lessonContext) {
          system += `\n\n--- ယခု ကျောင်းသား ဖတ်နေသော သင်ခန်းစာ ---\n${lessonContext}`;
        }
        if (currentQuestion) {
          system += `\n\n--- ကျောင်းသား လက်ရှိ ဖြေနေသော မေးခွန်း ---\n${currentQuestion}\n(သူဖြေနိုင်အောင် အကြံပြုပါ — အဖြေ တိုက်ရိုက် မပြောပါနှင့်၊ သူ မေးမှသာ ပြောပါ။)`;
        }

        const result = streamText({
          model,
          system: withTone(system),
          messages: await convertToModelMessages(messages as UIMessage[]),
        });

        return result.toUIMessageStreamResponse({
          originalMessages: messages as UIMessage[],
          onError: (error) => {
            console.error("[chat] stream error", error);
            const msg = error instanceof Error ? error.message : "Something went wrong.";
            if (msg.includes("429"))
              return "တောင်းဆိုမှု များနေပါသည် — ခဏစောင့်ပြီး ပြန်ကြိုးစားပါ။";
            if (msg.includes("402"))
              return "AI credits ကုန်ဆုံးနေပါသည်။ ဆက်လက်အသုံးပြုရန် credits ထပ်ဖြည့်ပါ။";
            return "ဆရာဇီးကွက် နည်းနည်း မအီးမသာ ဖြစ်နေပါတယ်။ ထပ်ကြိုးစားကြည့်ပါနော်။";
          },
        });
      },
    },
  },
});
