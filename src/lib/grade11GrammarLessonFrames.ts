export function grade11LessonOpening(topic: string, titleEn: string) {
  const lessonFrame = GRADE11_GRAMMAR_LESSON_FRAMES[topic];
  if (!lessonFrame) throw new Error(`Missing Grade 11 grammar foundation: ${topic}`);
  return [
    {
      titleMy: `သင်ခန်းစာမိတ်ဆက် · ${titleEn}`,
      scriptMy: `ဒီသင်ခန်းစာမှာ ${titleEn} ကို လေ့လာကြမယ်။ ${lessonFrame.meaningMy}`,
      noteMy: lessonFrame.meaningMy.split("။")[0] + "။",
    },
    {
      titleMy: "နမူနာမကြည့်မီ ပုံစံနှင့်အသုံးကို သိထားပါ",
      scriptMy: lessonFrame.patternSpeechMy,
      noteMy: lessonFrame.patternNoteMy,
    },
  ];
}
